#!/usr/bin/env node
// Writes src/config.js and capacitor.config.json for one environment, then runs
// `npx cap sync android`.
//
//   node scripts/build-config.js <local|staging|prod> [--api <url>] [--no-sync]
//
// --api replaces the API URL of the local build (a real phone on the LAN).
// --no-sync writes the two files without `cap sync` (no android/ folder needed).

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ENVIRONMENTS = ['local', 'staging', 'prod'];

export class BuildConfigError extends Error {}

export function parseArgs(argv) {
  const args = { env: null, api: null, sync: true };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--api') {
      const value = argv[++i];
      if (!value || value.startsWith('--')) throw new BuildConfigError('--api needs a URL.');
      args.api = value;
    } else if (arg.startsWith('--api=')) {
      args.api = arg.slice('--api='.length);
    } else if (arg === '--no-sync') {
      args.sync = false;
    } else if (arg.startsWith('--')) {
      throw new BuildConfigError(`Unknown option ${arg}.`);
    } else if (args.env === null) {
      args.env = arg;
    } else {
      throw new BuildConfigError(`Unexpected argument ${arg}.`);
    }
  }
  if (!ENVIRONMENTS.includes(args.env)) {
    throw new BuildConfigError(`Environment must be one of: ${ENVIRONMENTS.join(', ')}.`);
  }
  return args;
}

/** The API base URL without a trailing slash; throws when it is not an http(s) URL. */
export function normalizeUrl(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new BuildConfigError(`Not a valid URL: ${value}`);
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    throw new BuildConfigError(`The API URL must use http or https: ${value}`);
  }
  if (url.search || url.hash) {
    throw new BuildConfigError(`The API URL must not have a query or a fragment: ${value}`);
  }
  return url.toString().replace(/\/+$/, '');
}

/**
 * The build of one environment, without side effects.
 * @param {string} envKey local | staging | prod
 * @param {{ api?: string|null, envFile: object, baseConfig: object }} options
 * @returns {{ appConfig: object, configJs: string, capacitorConfig: object }}
 */
export function buildEnvironment(envKey, { api = null, envFile, baseConfig }) {
  const localBuild = envFile.localBuild === true;
  if (api && !localBuild) {
    throw new BuildConfigError(`--api is only accepted for the local build, not for ${envKey}.`);
  }
  const apiBaseUrl = normalizeUrl(api || envFile.apiBaseUrl);
  if (!localBuild && !apiBaseUrl.startsWith('https://')) {
    throw new BuildConfigError(
      `Refused: the ${envFile.name} build needs an https:// API URL, got ${apiBaseUrl}.`
    );
  }

  const appConfig = {
    API_BASE_URL: apiBaseUrl,
    ENV_NAME: envFile.name,
    LOCAL_BUILD: localBuild,
  };
  const configJs =
    '// GENERATED by scripts/build-config.js. Do not edit, do not commit.\n' +
    `window.APP_CONFIG = Object.freeze(${JSON.stringify(appConfig, null, 2)});\n`;

  const capacitorConfig = JSON.parse(JSON.stringify(baseConfig));
  if (localBuild) {
    // The page is https://localhost and the local API is plain HTTP.
    capacitorConfig.server = { ...(capacitorConfig.server || {}), cleartext: true };
    capacitorConfig.android = { ...(capacitorConfig.android || {}), allowMixedContent: true };
  } else {
    if (capacitorConfig.server) delete capacitorConfig.server.cleartext;
    if (capacitorConfig.android) delete capacitorConfig.android.allowMixedContent;
  }

  return { appConfig, configJs, capacitorConfig };
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function main(argv) {
  const args = parseArgs(argv);
  const envFile = readJson(path.join(ROOT, 'env', `${args.env}.json`));
  const baseConfig = readJson(path.join(ROOT, 'env', 'capacitor.base.json'));
  const { appConfig, configJs, capacitorConfig } = buildEnvironment(args.env, {
    api: args.api,
    envFile,
    baseConfig,
  });

  fs.writeFileSync(path.join(ROOT, 'src', 'config.js'), configJs);
  fs.writeFileSync(
    path.join(ROOT, 'capacitor.config.json'),
    JSON.stringify(capacitorConfig, null, 2) + '\n'
  );

  if (args.sync) {
    const result = spawnSync('npx', ['cap', 'sync', 'android'], { cwd: ROOT, stdio: 'inherit' });
    if (result.status !== 0) {
      throw new BuildConfigError('npx cap sync android failed.');
    }
  }

  console.log(`\n  Environment: ${appConfig.ENV_NAME}`);
  console.log(`  API:         ${appConfig.API_BASE_URL}`);
  console.log(`  Local build: ${appConfig.LOCAL_BUILD}${args.sync ? '' : '  (cap sync skipped)'}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    if (error instanceof BuildConfigError) {
      console.error(`build-config: ${error.message}`);
      process.exit(1);
    }
    throw error;
  }
}
